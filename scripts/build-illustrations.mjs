// Generates src/assets/illustrations/*.svg from Microsoft Fluent Emoji (flat style, MIT).
// It scans the app source for every emoji the app shows and writes one SVG per emoji,
// named by its codepoints without FE0F (for example 1f34e.svg for the red apple).
// Run with: npm run illustrations
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = path.join(root, 'node_modules', '@iconify-json', 'fluent-emoji-flat');
const outDir = path.join(root, 'src', 'assets', 'illustrations');
const srcDir = path.join(root, 'src');

const icons = JSON.parse(fs.readFileSync(path.join(pkg, 'icons.json'), 'utf8'));
const chars = JSON.parse(fs.readFileSync(path.join(pkg, 'chars.json'), 'utf8'));
const info = JSON.parse(fs.readFileSync(path.join(pkg, 'info.json'), 'utf8'));
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;

export function emojiKey(emoji) {
  return [...emoji]
    .map((char) => char.codePointAt(0).toString(16))
    .filter((code) => code !== 'fe0f')
    .join('-');
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return full === outDir || entry.name === 'node_modules' ? [] : walk(full);
    if (!/\.(ts|tsx)$/.test(entry.name) || /\.test\.tsx?$/.test(entry.name)) return [];
    return [full];
  });
}

const emojiPattern = /\p{RGI_Emoji}/gv;
const found = new Map();
// Lesson content shared with the phone app lives in packages/, outside src/: scan it too,
// or its pictures would be deleted as unused.
const packagesDir = path.join(root, 'packages');
const sourceDirs = [srcDir, ...(fs.existsSync(packagesDir) ? [packagesDir] : [])];
for (const file of sourceDirs.flatMap((dir) => walk(dir))) {
  const text = fs.readFileSync(file, 'utf8');
  for (const match of text.matchAll(emojiPattern)) {
    const key = emojiKey(match[0]);
    if (!found.has(key)) found.set(key, { emoji: match[0], files: new Set() });
    found.get(key).files.add(path.relative(root, file));
  }
}

function iconBody(name) {
  const icon = icons.icons[name];
  if (icon) return { body: icon.body, width: icon.width ?? icons.width, height: icon.height ?? icons.height };
  const alias = icons.aliases?.[name];
  if (alias) return iconBody(alias.parent);
  return null;
}

const unsafe = /<script|\son[a-z]+\s*=|(?:xlink:)?href\s*=\s*["'](?!#)|<foreignObject|javascript:/i;

fs.mkdirSync(outDir, { recursive: true });
for (const file of fs.readdirSync(outDir)) {
  if (file.endsWith('.svg')) fs.rmSync(path.join(outDir, file));
}

const written = [];
const missing = [];
for (const [key, { emoji, files }] of [...found.entries()].sort()) {
  const name = chars[key];
  const icon = name ? iconBody(name) : null;
  if (!icon) {
    missing.push(`${emoji} (${key}) in ${[...files].join(', ')}`);
    continue;
  }
  if (unsafe.test(icon.body)) throw new Error(`Refusing unsafe SVG markup for ${name}`);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${icon.width} ${icon.height}" width="${icon.width}" height="${icon.height}">${icon.body}</svg>\n`;
  fs.writeFileSync(path.join(outDir, `${key}.svg`), svg);
  written.push(`${emoji} ${key} ${name}`);
}

